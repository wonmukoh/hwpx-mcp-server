/**
 * 인라인 꾸밈 — **한 문단 안에서 어구마다 굵기·색이 바뀌는 것.**
 *
 * ## 왜 있어야 하나
 *
 * 정부 문서의 지배적인 무늬다. 실측 (교육부 2026 업무계획 본문 101문단):
 *
 * | 한 문단에 글 든 런이 | 문단 수 |
 * |---|---|
 * | 1개 | 25 |
 * | 2~5개 | 20 |
 * | 10개 넘음 | 26 |
 * | **28개** | 2 |
 * | **42개** | 1 |
 *
 * 문단 하나가 런 28개로 쪼개져 있다. 어구마다 굵게가 걸려 있기 때문이다.
 * 이걸 도구 호출 28번으로 만들 수는 없다. **글 안에 표시해서 한 번에** 받는다.
 *
 * ## 표시법
 *
 * ```
 * **굵게**          →  굵은 글자
 * [[강조]]          →  강조색 (기본 파랑 #0000FF)
 * **[[둘 다]]**     →  겹쳐 쓸 수 있다. 순서는 상관없다
 * \**              →  별표를 글자 그대로 쓰고 싶을 때
 * ```
 *
 * ## 색과 굵기는 **따로다**
 *
 * 처음엔 "파란 글자는 늘 굵다" 고 여겼다. 세어 보니 아니었다 —
 * `#0000FF` 가 쓰인 charPr 267개 가운데 **굵게 97 / 보통 170**.
 * 그래서 `[[…]]` 는 **색만** 건다. 굵게 하려면 `**[[…]]**` 처럼 겹쳐 쓴다.
 *
 * ## 안 닫히면 조용히 넘어가지 않는다
 *
 * `**` 가 하나만 있으면 어디까지 굵게인지 알 수 없다.
 * 그럴 때 그냥 두면 문서가 통째로 굵어진다. **몇 번째 글자인지 짚어 준다.**
 */

import { 됨, 안됨, type 결과 } from '@hwpx/doc';

export interface 글조각 {
  글: string;
  굵게: boolean;
  /** 강조색. 안 주면 문단의 바탕 색 */
  색?: string;
}

export interface 꾸밈설정 {
  /** `[[…]]` 에 쓸 색. 실측: 정부 문서가 `#0000FF` 를 267번 썼다 */
  강조색?: string;
}

const 기본강조색 = '#0000FF';

/** 표시가 하나라도 들어 있나 (없으면 굳이 쪼개지 않는다) */
export function 꾸밈있나(글: string): boolean {
  return 글.includes('**') || 글.includes('[[') || 글.includes(']]');
}

/**
 * 표시를 풀어 조각들로.
 *
 * 표시가 없으면 조각 하나를 돌려준다.
 */
export function 꾸밈풀기(글: string, 설정: 꾸밈설정 = {}): 결과<글조각[]> {
  const 강조색 = 설정.강조색 ?? 기본강조색;
  const 조각들: 글조각[] = [];

  let 담을것 = '';
  let 굵게 = false;
  let 색깊이 = 0;
  // 안 닫힌 것을 짚어 주려고 연 자리를 들고 있는다
  let 굵게연자리 = -1;
  let 색연자리 = -1;

  const 내려놓기 = () => {
    if (담을것.length === 0) return;
    조각들.push(색깊이 > 0 ? { 글: 담을것, 굵게, 색: 강조색 } : { 글: 담을것, 굵게 });
    담을것 = '';
  };

  let i = 0;
  while (i < 글.length) {
    const 이번 = 글[i]!;

    // 글자 그대로 쓰기
    if (이번 === '\\' && i + 1 < 글.length && '*[]\\'.includes(글[i + 1]!)) {
      담을것 += 글[i + 1];
      i += 2;
      continue;
    }

    if (글.startsWith('**', i)) {
      내려놓기();
      굵게 = !굵게;
      굵게연자리 = 굵게 ? i : -1;
      i += 2;
      continue;
    }

    if (글.startsWith('[[', i)) {
      내려놓기();
      if (색깊이 === 0) 색연자리 = i;
      색깊이++;
      i += 2;
      continue;
    }

    if (글.startsWith(']]', i)) {
      if (색깊이 === 0) {
        return 안됨(
          `${i}번째 글자에서 ']]' 가 '[[' 없이 나왔다`,
          `글자 그대로 쓰려면 '\\]\\]' 로 적어라. 글: «${둘레(글, i)}»`,
        );
      }
      내려놓기();
      색깊이--;
      if (색깊이 === 0) 색연자리 = -1;
      i += 2;
      continue;
    }

    담을것 += 이번;
    i++;
  }
  내려놓기();

  if (굵게) {
    return 안됨(
      `${굵게연자리}번째 글자에서 연 '**' 가 안 닫혔다`,
      `굵게 할 데를 '**말**' 처럼 양쪽에 적어라. 글: «${둘레(글, 굵게연자리)}»`,
    );
  }
  if (색깊이 > 0) {
    return 안됨(
      `${색연자리}번째 글자에서 연 '[[' 가 안 닫혔다`,
      `강조할 데를 '[[말]]' 처럼 양쪽에 적어라. 글: «${둘레(글, 색연자리)}»`,
    );
  }

  // 표시만 있고 글이 없으면 빈 조각 하나를 준다 (빈 문단도 만들 수 있어야 한다)
  if (조각들.length === 0) 조각들.push({ 글: '', 굵게: false });
  return 됨(조각들);
}

/** 표시를 걷어 낸 맨 글 (찾기·견주기에 쓴다) */
export function 꾸밈걷기(글: string): string {
  const r = 꾸밈풀기(글);
  if (!r.ok) {
    // 못 풀면 표시만 지워 준다 — 여기서 던지면 오류 메시지도 못 만든다
    return 글.replace(/\\([*[\]\\])/g, '$1').split('**').join('').split('[[').join('').split(']]').join('');
  }
  return r.value.map((x) => x.글).join('');
}

/** 오류에 보여 줄 앞뒤 글 */
function 둘레(글: string, 자리: number, 폭 = 24): string {
  const a = Math.max(0, 자리 - 폭);
  const b = Math.min(글.length, 자리 + 폭);
  return (a > 0 ? '…' : '') + 글.slice(a, b) + (b < 글.length ? '…' : '');
}
